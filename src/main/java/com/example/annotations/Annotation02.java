package com.example.annotations;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

// Stored in class file as RuntimeVisibleAnnotations, readable via reflection
@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.TYPE)
@interface MyComponent {
    String value() default "";
}

// Stored in class file as RuntimeInvisibleAnnotations, not readable via reflection
@Retention(RetentionPolicy.CLASS)
@Target(ElementType.TYPE)
@interface ClassOnly {}

@MyComponent("bean1")
@ClassOnly
public class Annotation02 {

    public static void main(String[] args) {
        MyComponent c = Annotation02.class.getAnnotation(MyComponent.class);
        System.out.println("MyComponent present: " + (c != null) + ", value=" + (c != null ? c.value() : null));
        System.out.println("ClassOnly present: " + Annotation02.class.isAnnotationPresent(ClassOnly.class));

        // Customer getters/setters are generated by Lombok
        Customer customer = new Customer();
        customer.setFirstName("John");
        customer.setLastName("Smith");
        System.out.println("Customer: " + customer.getFirstName() + " " + customer.getLastName());
    }
}
